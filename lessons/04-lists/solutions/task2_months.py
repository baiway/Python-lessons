months = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]

print(months[:3])    # first three months
print(months[-3:])   # last three months
print(months[5:8])   # June (index 5), July and August (index 7)
print(months[::2])   # every other month
print(months[::-1])  # reverse order
