import math

# Calculate surface areas using s = 2a^2 sqrt(3)
s1 = 2 * 1**2 * math.sqrt(3)
s2 = 2 * 2**2 * math.sqrt(3)
s3 = 2 * 3**2 * math.sqrt(3)
s4 = 2 * 4**2 * math.sqrt(3)

print(f"The surface area of an octahedron with side length 1 cm is {s1:.2f} cm^2.")
print(f"The surface area of an octahedron with side length 2 cm is {s2:.2f} cm^2.")
print(f"The surface area of an octahedron with side length 3 cm is {s3:.2f} cm^2.")
print(f"The surface area of an octahedron with side length 4 cm is {s4:.2f} cm^2.")
